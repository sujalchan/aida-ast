use std::{
    error::Error,
    fs,
    path::{Path, PathBuf},
};

mod aida;
mod extractor;
mod parser;
mod rust;

fn main() -> Result<(), Box<dyn Error>> {
    let mut arguments = std::env::args().skip(1).collect::<Vec<_>>();
    let fast_math_count = arguments
        .iter()
        .filter(|argument| argument.as_str() == "--fast-math")
        .count();
    if fast_math_count > 1 {
        return Err("--fast-math may only be specified once".into());
    }
    let fast_math = fast_math_count == 1;
    arguments.retain(|argument| argument != "--fast-math");
    let mut args = arguments.into_iter();
    match args.next().as_deref() {
        Some("--tests") if args.next().is_none() => return compile_tests(fast_math),
        Some("--runtime") => {
            let output = args
                .next()
                .ok_or("usage: aida-ast [--fast-math] --runtime <output.rs> <input.sb3>")?;
            let input = args
                .next()
                .ok_or("usage: aida-ast [--fast-math] --runtime <output.rs> <input.sb3>")?;
            if args.next().is_some() {
                return Err(
                    "usage: aida-ast [--fast-math] --runtime <output.rs> <input.sb3>".into(),
                );
            }
            return compile_runtime_module(&input, &output, fast_math);
        }
        Some(argument) => {
            return Err(format!("unknown argument: {argument}\nusage: aida-ast [--fast-math] [--tests] | --runtime <output.rs> <input.sb3>").into());
        }
        None => {}
    }

    let sb3_input = "example.sb3";
    let json_output = "project.json";
    let aida_output = "project.aida";

    extractor::extract_project_json(sb3_input, json_output)?;
    println!("Extracted {json_output} from {sb3_input}");

    let json_str = fs::read_to_string(json_output)?;

    let project = parser::parse_project(&json_str)?;
    parser::print_project(&project);

    fs::write(aida_output, aida::generate(&project))?;
    println!("Generated {aida_output}");

    Ok(())
}

fn compile_runtime_module(
    input: &str,
    output: &str,
    fast_math: bool,
) -> Result<(), Box<dyn Error>> {
    let json = extractor::read_project_json(input)?;
    let project = parser::parse_project(&json)?;
    let generated = if fast_math {
        rust::generate_with_options(&project, true)
    } else {
        rust::generate(&project)
    };
    let mode_comment = if fast_math {
        "// fast math enabled; scratch edge-case compatibility is relaxed.\n"
    } else {
        ""
    };
    let module = format!(
        "// Generated by aida-ast from {}. Do not edit by hand.\n{mode_comment}{}",
        Path::new(input).display(),
        generated
    );
    fs::write(output, module)?;
    if fast_math {
        println!("Generated fast-math runtime module {output} from {input}");
    } else {
        println!("Generated runtime module {output} from {input}");
    }
    Ok(())
}

fn compile_tests(fast_math: bool) -> Result<(), Box<dyn Error>> {
    let crate_dir = Path::new(env!("CARGO_MANIFEST_DIR"));
    let source_dir = crate_dir.join("tests/src");
    let output_dir = crate_dir.join("tests/output");
    fs::create_dir_all(&output_dir)?;

    let mut inputs: Vec<PathBuf> = fs::read_dir(source_dir)?
        .map(|entry| entry.map(|entry| entry.path()))
        .collect::<Result<_, _>>()?;
    inputs.retain(|path| {
        path.is_file()
            && path
                .extension()
                .is_some_and(|extension| extension.eq_ignore_ascii_case("sb3"))
    });
    inputs.sort();

    for input in &inputs {
        let json = extractor::read_project_json(input)?;
        let project = parser::parse_project(&json)?;
        let output_name = input
            .file_stem()
            .ok_or("test project has no filename")?
            .to_string_lossy();
        let output = output_dir.join(format!("{output_name}.rs"));
        let generated = if fast_math {
            rust::generate_with_options(&project, true)
        } else {
            rust::generate(&project)
        };
        fs::write(&output, generated)?;
        println!("Compiled {} -> {}", input.display(), output.display());
    }

    println!("Compiled {} test project(s)", inputs.len());
    Ok(())
}
